package query

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/hmac"
	"crypto/sha256"
	"encoding/base64"
	"encoding/json"
	"errors"
	"time"
)

const (
	cursorDomain         = "sentinel/dashboard/alert-page/v1"
	minCursorSecretBytes = 32
)

// CursorCodec authenticates and encrypts bounded versioned page positions.
// Replicas sharing the validated JWT secret can continue each other's pages.
type CursorCodec struct{ aead cipher.AEAD }
type cursorPayload struct {
	Version  int          `json:"v"`
	Endpoint string       `json:"endpoint"`
	Tenant   string       `json:"tenant"`
	Filters  AlertFilters `json:"filters"`
	Position Position     `json:"after"`
}

// NewCursorCodec derives a separate encryption key from validated auth material.
// Key rotation deliberately invalidates existing cursors along with sessions.
func NewCursorCodec(secret []byte) (*CursorCodec, error) {
	if len(secret) < minCursorSecretBytes {
		return nil, errors.New("cursor key requires at least 32 bytes")
	}
	derive := hmac.New(sha256.New, secret)
	_, _ = derive.Write([]byte(cursorDomain))
	block, err := aes.NewCipher(derive.Sum(nil))
	if err != nil {
		return nil, err
	}
	aead, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, err
	}
	return &CursorCodec{aead: aead}, nil
}

// Encode never exposes tenant/filter material as unauthenticated public bytes.
func (c *CursorCodec) Encode(endpoint, tenant string, f AlertFilters, after Position) (string, error) {
	f.Cursor = ""
	if !validCursorPayload(endpoint, tenant, f, after) {
		return "", ErrInvalidQuery
	}
	raw, err := json.Marshal(cursorPayload{Version: 1, Endpoint: endpoint, Tenant: tenant, Filters: f, Position: after})
	if err != nil {
		return "", ErrInvalidQuery
	}
	// NewGCMWithRandomNonce generates and prepends its own random nonce; its
	// NonceSize is zero and the nonce argument is required to be nil.
	sealed := c.aead.Seal(nil, nil, raw, []byte(cursorDomain)) //nolint:gosec // G407: nonce is generated by AEAD.
	encoded := base64.RawURLEncoding.EncodeToString(sealed)
	if len(encoded) > maxCursorBytes {
		return "", ErrInvalidQuery
	}
	return encoded, nil
}

// Decode compares all normalized filters and freezes omitted time defaults.
func (c *CursorCodec) Decode(token, endpoint, tenant string, f AlertFilters) (AlertFilters, Position, error) {
	invalid := func() (AlertFilters, Position, error) { return AlertFilters{}, Position{}, ErrInvalidQuery }
	if token == "" || len(token) > maxCursorBytes {
		return invalid()
	}
	raw, err := base64.RawURLEncoding.Strict().DecodeString(token)
	if err != nil {
		return invalid()
	}
	plain, err := c.aead.Open(nil, nil, raw, []byte(cursorDomain))
	if err != nil {
		return invalid()
	}
	var payload cursorPayload
	if json.Unmarshal(plain, &payload) != nil || payload.Version != 1 ||
		payload.Endpoint != endpoint || payload.Tenant != tenant ||
		!validCursorPayload(payload.Endpoint, payload.Tenant, payload.Filters, payload.Position) {
		return invalid()
	}
	if f.From.IsZero() {
		f.From = payload.Filters.From
	}
	if f.To.IsZero() {
		f.To = payload.Filters.To
	}
	if normalizeAlertFilters(&f, payload.Filters.To) != nil || f != payload.Filters {
		return invalid()
	}
	return f, payload.Position, nil
}
func validCursorPayload(endpoint, tenant string, f AlertFilters, after Position) bool {
	return (endpoint == "alerts" || endpoint == "events") && tenantID.MatchString(tenant) &&
		!f.From.IsZero() && !f.To.IsZero() && f.Cursor == "" && normalizeAlertFilters(&f, f.To) == nil &&
		!after.CreatedAt.Before(f.From) && after.CreatedAt.Before(f.To) &&
		after.CreatedAt.Equal(after.CreatedAt.Truncate(time.Millisecond)) && alertID.MatchString(after.AlertID)
}
